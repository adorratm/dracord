function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j]!, a[i]!];
  }
  return a;
}

function uid(prefix: string): string {
  return `${prefix}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
}

/** Matematik sorusu — sınırsız varyasyon */
export function triviaGenerateMath(): TriviaQuestion {
  const kind = Math.floor(Math.random() * 4);
  let q: string;
  let correctVal: number;
  if (kind === 0) {
    const a = 2 + Math.floor(Math.random() * 20);
    const b = 2 + Math.floor(Math.random() * 20);
    correctVal = a + b;
    q = `${a} + ${b} kaçtır?`;
  } else if (kind === 1) {
    const a = 5 + Math.floor(Math.random() * 30);
    const b = 1 + Math.floor(Math.random() * Math.min(12, a - 1));
    correctVal = a - b;
    q = `${a} − ${b} kaçtır?`;
  } else if (kind === 2) {
    const a = 2 + Math.floor(Math.random() * 12);
    const b = 2 + Math.floor(Math.random() * 10);
    correctVal = a * b;
    q = `${a} × ${b} kaçtır?`;
  } else {
    const b = 2 + Math.floor(Math.random() * 9);
    const correctValInner = 2 + Math.floor(Math.random() * 12);
    const a = b * correctValInner;
    correctVal = correctValInner;
    q = `${a} ÷ ${b} kaçtır?`;
  }
  const distractors = new Set<number>();
  while (distractors.size < 3) {
    const delta = (Math.floor(Math.random() * 9) + 1) * (Math.random() < 0.5 ? -1 : 1);
    const v = correctVal + delta;
    if (v !== correctVal && v >= 0) distractors.add(v);
  }
  const opts = shuffle([correctVal, ...distractors].map(String)) as [
    string,
    string,
    string,
    string,
  ];
  return {
    id: uid('math'),
    q,
    options: opts,
    correct: opts.indexOf(String(correctVal)) as 0 | 1 | 2 | 3,
  };
}

/** Başkent sorusu */
export function triviaGenerateCapital(): TriviaQuestion {
  const row = CAPITALS[Math.floor(Math.random() * CAPITALS.length)]!;
  const options = shuffle([row.country, ...row.distractors]) as [
    string,
    string,
    string,
    string,
  ];
  return {
    id: uid('cap'),
    q: `${row.city} hangi ülkenin başkentidir?`,
    options,
    correct: options.indexOf(row.country) as 0 | 1 | 2 | 3,
  };
}

/** Ücretsiz “AI benzeri” üretici: banka + prosedürel karışım */
export function triviaGenerateQuestion(usedIds: string[] = []): TriviaQuestion {
  const pool = TRIVIA_BANK.filter((q) => !usedIds.includes(q.id));
  const roll = Math.random();
  if (roll < 0.35 || pool.length === 0) {
    return Math.random() < 0.55 ? triviaGenerateMath() : triviaGenerateCapital();
  }
  return pool[Math.floor(Math.random() * pool.length)]!;
}
