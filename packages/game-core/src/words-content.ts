/** Tekrarları temizle, küçük harf TR */
export function wordsNormalizeBank(bank: string[] = WORD_BANK): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const w of bank) {
    const n = w.trim().toLocaleLowerCase('tr-TR');
    if (n.length < 3 || seen.has(n)) continue;
    if (!/^[a-zçğıöşü]+$/i.test(n)) continue;
    seen.add(n);
    out.push(n);
  }
  return out;
}

const NORMALIZED = wordsNormalizeBank();

export function wordsPickFromBank(used: string[] = []): string {
  const pool = NORMALIZED.filter((w) => !used.includes(w));
  const list = pool.length ? pool : NORMALIZED;
  return list[Math.floor(Math.random() * list.length)]!;
}
